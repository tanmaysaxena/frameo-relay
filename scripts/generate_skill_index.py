#!/usr/bin/env python3
"""Regenerate SKILLS.md from each skill's SKILL.md frontmatter (stdlib only).

Usage: python scripts/generate_skill_index.py [--check]
--check exits 1 if SKILLS.md is stale (for CI or a pre-commit habit).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def frontmatter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def build():
    rows = []
    sdir = os.path.join(ROOT, "skills")
    for name in sorted(os.listdir(sdir)):
        p = os.path.join(sdir, name, "SKILL.md")
        if os.path.isfile(p):
            fm = frontmatter(p)
            rows.append((fm.get("name", name), fm.get("description", "")))
    lines = ["# Skills", "", "Generated by `scripts/generate_skill_index.py`. Do not edit by hand.", "",
             "| Skill | What it does |", "|---|---|"]
    for n, desc in rows:
        lines.append(f"| `frameorelay:{n}` | {desc.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = os.path.join(ROOT, "SKILLS.md")
    new = build()
    if "--check" in sys.argv:
        old = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        sys.exit(0 if old == new else 1)
    open(target, "w", encoding="utf-8", newline="\n").write(new)
    print("wrote SKILLS.md")
